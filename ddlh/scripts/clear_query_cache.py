"""
Delete every cached query summary, so that they are regenerated by the
model currently configured in MISTRAL_LANGUAGE_MODEL_NAME (for example, to
drop summaries generated by Mixtral). Cached summaries never expire, so
this is the way to refresh them:

    python -m ddlh.scripts.clear_query_cache
"""

from os import environ

from ddlh.redis_cache import create_cache


def clear_query_cache() -> int:
    cache = create_cache(prefix=environ["REDIS_QUERY_CACHE_PREFIX"])
    return cache.clear()


if __name__ == "__main__":
    deleted = clear_query_cache()
    print(f"Deleted {deleted} cached query summaries")
